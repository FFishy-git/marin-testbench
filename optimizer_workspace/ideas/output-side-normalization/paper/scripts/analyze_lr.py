"""Build the learning-rate study's numbers and figure data.

The 28 short-schedule screening trials live under campaigns/, not runs/: seven
matrix learning rates for each of four families, 320 updates and 167,772,160
tokens per trial. Ranking uses the final reserved-mixture selection loss only,
as the study's own protocol specifies; C4 is reporting-only.

    python -I scripts/analyze_lr.py
"""

import json
import os
from collections import OrderedDict

PVC = "/apdcephfs_tj32/share_303214315/hunyuan/kenanchen/toner/output-side-normalization"
CAMPAIGNS = os.path.join(PVC, "campaigns")
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

BASE_LR = 0.02262741696

# Each screening point: label, multiplier of the recipe LR, absolute LR, and
# the campaign directory plus run-name suffix that holds its four trials.
POINTS = [
    ("down", 1 / 2**0.5, 0.015999999973151494, "lr-fixed-age-0p5m-20261116", "lr_down"),
    ("base", 1.0, 0.02262741696, "lr-fixed-age-0p5m-20261116", "lr_base"),
    ("up", 2**0.5, 0.03199999994630299, "lr-fixed-age-0p5m-20261116", "lr_up"),
    ("2x", 2.0, 0.04525483392, "lr-fixed-age-upper-boundary-0p5m-20261117", "lr_expand_2x"),
    ("2sqrt2x", 2 * 2**0.5, 0.06399999989260598, "lr-fixed-age-upper-boundary-0p5m-20261117", "lr_expand_2sqrt2x"),
    ("4x", 4.0, 0.09050966784, "lr-fixed-age-ceiling-visible8-recovery-20261117", "lr_ceiling_4x"),
    ("4sqrt2x", 4 * 2**0.5, 0.12799999978521195, "lr-fixed-age-ceiling-visible8-recovery-20261117", "lr_ceiling_4sqrt2x"),
]

FAMILIES = ["muont", "inner_outer_leftdiag", "outer_leftdiag", "outer_leftdiag_fused"]


def final_eval(campaign, run):
    path = os.path.join(CAMPAIGNS, campaign, "runs", run, "metrics_from_000000.jsonl")
    if not os.path.exists(path):
        return None
    best = None
    with open(path) as handle:
        for line in handle:
            line = line.strip()
            if not line:
                continue
            row = json.loads(line)
            if row.get("selection_loss") is not None:
                if best is None or row["step"] >= best["step"]:
                    best = row
    return best


table = OrderedDict()
for label, mult, lr, campaign, suffix in POINTS:
    for family in FAMILIES:
        row = final_eval(campaign, f"{family}_{suffix}")
        if row is None:
            print(f"missing: {campaign}/{family}_{suffix}")
            continue
        table[(label, family)] = dict(
            lr=lr, mult=mult, updates=row["step"],
            selection=row["selection_loss"], c4=row["c4_loss"],
            seconds=row.get("end_to_end_seconds"),
        )

# Figure: selection loss against matrix learning rate, one line per family.
lines = ["lr mult " + " ".join(FAMILIES) + " " + " ".join(f + "_t" for f in FAMILIES)]
for label, mult, lr, _, _ in POINTS:
    sel = [table.get((label, f), {}).get("selection") for f in FAMILIES]
    sec = [table.get((label, f), {}).get("seconds") for f in FAMILIES]
    cells = [f"{lr:.8g}", f"{mult:.6g}"]
    cells += ["nan" if v is None else f"{v:.6f}" for v in sel]
    cells += ["nan" if v is None else f"{v:.1f}" for v in sec]
    lines.append(" ".join(cells))
with open(os.path.join(HERE, "figs", "lr_sweep.dat"), "w") as handle:
    handle.write("\n".join(lines) + "\n")

# Per-family best point and its margin over the independently selected baseline.
best = {}
for family in FAMILIES:
    pts = [(table[(l, family)]["selection"], l, table[(l, family)]["lr"])
           for l, _, _, _, _ in POINTS if (l, family) in table]
    best[family] = min(pts)

print(f"{'family':24s} {'best LR':>12s} {'point':>9s} {'selection':>11s} {'vs muont':>11s} interior")
for family in FAMILIES:
    sel, label, lr = best[family]
    margin = sel - best["muont"][0]
    interior = label not in {"down", "4sqrt2x"}
    print(f"{family:24s} {lr:12.8f} {label:>9s} {sel:11.6f} {margin:+11.6f} {interior}")

print()
print("selection loss by family and LR (320-update schedule):")
print(f"{'point':>9s} {'LR':>11s} " + " ".join(f"{f[:18]:>18s}" for f in FAMILIES))
for label, mult, lr, _, _ in POINTS:
    cells = [f"{label:>9s}", f"{lr:11.6f}"]
    for family in FAMILIES:
        rec = table.get((label, family))
        cells.append(f"{rec['selection']:18.6f}" if rec else f"{'--':>18s}")
    print(" ".join(cells))

# LaTeX macros for the numbers the prose quotes.
out = ["% Generated by scripts/analyze_lr.py from the screening trials. Do not edit.\n"]


def mac(name, value, places=6):
    out.append(f"\\newcommand{{\\{name}}}{{{value:.{places}f}}}")


mac("lrMuontBest", best["muont"][0])
mac("lrMuontBestLR", best["muont"][2], 5)
mac("lrMuontBase", table[("base", "muont")]["selection"])
mac("lrMuontGainFromTuning", table[("base", "muont")]["selection"] - best["muont"][0])
for family in FAMILIES:
    stem = "".join(p.capitalize() for p in family.split("_"))
    mac(f"lrBest{stem}", best[family][0])
    mac(f"lrBestLR{stem}", best[family][2], 5)
    mac(f"lrMargin{stem}", best[family][0] - best["muont"][0])
    mac(f"lrBase{stem}", table[("base", family)]["selection"])
    mac(f"lrSameLRMargin{stem}",
        table[("base", family)]["selection"] - table[("base", "muont")]["selection"])
with open(os.path.join(HERE, "results", "lr_numbers.tex"), "w") as handle:
    handle.write("\n".join(out) + "\n")

with open(os.path.join(HERE, "results", "lr_summary.json"), "w") as handle:
    json.dump({f"{l}/{f}": v for (l, f), v in table.items()}, handle, indent=1, sort_keys=True)
