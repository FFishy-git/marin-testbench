"""Derive cross-study, Wave-12 horizon, and wave_sym_fastlag macros quoted in prose.

Reads results/summary.json, results/lr_summary.json, and results/sym_wave_raw.json
and writes results/derived_numbers.tex.

    python -I scripts/derive.py
"""

import json
import os

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

with open(os.path.join(HERE, "results", "summary.json")) as handle:
    runs = json.load(handle)
with open(os.path.join(HERE, "results", "lr_summary.json")) as handle:
    lr = json.load(handle)
with open(os.path.join(HERE, "results", "sym_wave_raw.json")) as handle:
    sym_raw = json.load(handle)

out = ["% Generated by scripts/derive.py. Do not edit.\n"]


def mac(name, text):
    out.append(f"\\newcommand{{\\{name}}}{{{text}}}")


# Headline held-out deltas, as magnitudes for prose that supplies its own sign.
best = runs["wave2/inner_outer_mlpdiag"]["d_sel_late"]
mac("mlpdiagsel", f"{best:.4f}")
mac("mlpdiagselmag", f"{abs(best):.4f}")
mac("leftallsel", f"{runs['wave1/left_all']['d_sel_late']:+.4f}")
mac("nullallsel", f"{runs['wave1/null_all']['d_sel_late']:+.6f}")
mac("nullmlpsel", f"{runs['wave3/null_mlpdiag']['d_sel_late']:+.6f}")
mac("nullmlpselFour", f"{runs['wave3/null_mlpdiag']['d_sel_late']:+.4f}")

# Share of the apparent gain that the matched null already accounts for.
dense = runs["wave1/inner_outer_all"]["d_sel_late"]
nulld = runs["wave1/null_all"]["d_sel_late"]
mac("nullsharedense", f"{100.0 * nulld / dense:.0f}")
mac(
    "nullsharemlpcfour",
    f"{100.0 * runs['wave3/null_mlpdiag']['d_c4_late'] / runs['wave2/inner_outer_mlpdiag']['d_c4_late']:.0f}",
)

# Worst full-budget transferred-rate regression, as a positive magnitude.
transfer = [
    runs[k]["d_sel_late"]
    for k in ("wave12/inner_outer_leftdiag", "wave12/outer_leftdiag")
]
mac("transferWorst", f"{max(transfer):.3f}")

# Learning-rate headroom on the 320-step screening schedule.
muont_base = lr["base/muont"]["selection"]
muont_best = min(v["selection"] for k, v in lr.items() if k.endswith("/muont"))
headroom = muont_base - muont_best
mac("lrHeadroom", f"{headroom:.3f}")
mac("lrHeadroomRatio", f"{headroom / abs(best):.0f}")

for fam in ("inner_outer_leftdiag", "outer_leftdiag", "outer_leftdiag_fused"):
    stem = "".join(p.capitalize() for p in fam.split("_"))
    short = lr[f"base/{fam}"]["selection"] - muont_base
    mac(f"shortBase{stem}", f"{short:+.6f}")

# Full-budget horizon shift: MuonT at 0.064 (wave 12) vs. 0.0226 (wave 10).
w12_sel_diff = runs["wave12/muont"]["sel_late"] - runs["wave10/muont"]["sel_late"]
w12_c4_diff = runs["wave12/muont"]["c4_final"] - runs["wave10/muont"]["c4_final"]
mac("waveTwelveMuontSelDiff", f"{w12_sel_diff:+.4f}")
mac("waveTwelveMuontSelDiffMag", f"{abs(w12_sel_diff):.3f}")
mac("waveTwelveMuontCfourDiff", f"{w12_c4_diff:+.4f}")

# ---------------------------------------------------------------------------
# Uncontended 8xA100 wave_sym_fastlag quality, 5-window, and parity macros.
# ---------------------------------------------------------------------------
par = sym_raw["muont_same_wave_vs_wave0_parity"]
sr = sym_raw["runs"]
h2h = sym_raw["head_to_head"]

r_mu = sr["wave_sym_fastlag/muont"]
r_sym = sr["wave_sym_fastlag/inner_outer_sym_mlpdiag"]
r_symlag = sr["wave_sym_fastlag/inner_outer_sym_mlpdiag_lag"]
r_mlplag = sr["wave_sym_fastlag/inner_outer_mlpdiag_lag"]

mac("symWaveExactSteps", f"{par['exact_train_steps']}")
mac("symWaveMuontInFb", f"{par['input_fallbacks_a']}")
mac("waveZeroMuontInFb", f"{par['input_fallbacks_b']}")
mac("symWaveMuontVsWaveZeroSel", f"{r_mu['vs_wave0_muont']['d_sel_late']:+.4f}")
mac("symWaveMuontVsWaveZeroSelSix", f"{r_mu['vs_wave0_muont']['d_sel_late']:+.6f}")
mac("symWaveMuontVsWaveZeroCfourFinal", f"{r_mu['vs_wave0_muont']['d_c4_final']:+.4f}")
mac("symWaveMuontCfourFinalAbs", f"{r_mu['c4_final']:.4f}")
mac("waveZeroMuonCfourFinalAbs", f"{sr['wave0/muon']['c4_final']:.4f}")

# WT-MLP-Lag (fast_lag, wave_sym_fastlag)
mac("fastMlpLagSelSame", f"{r_mlplag['vs_same_wave_muont']['d_sel_late']:+.4f}")
mac("fastMlpLagSelWaveZero", f"{r_mlplag['vs_wave0_muont']['d_sel_late']:+.4f}")
mac("fastMlpLagSelFinalSame", f"{r_mlplag['vs_same_wave_muont']['d_sel_final']:+.4f}")
mac("fastMlpLagSelFinalWaveZero", f"{r_mlplag['vs_wave0_muont']['d_sel_final']:+.4f}")
mac("fastMlpLagCfourSame", f"{r_mlplag['vs_same_wave_muont']['d_c4_late']:+.4f}")
mac("fastMlpLagCfourWaveZero", f"{r_mlplag['vs_wave0_muont']['d_c4_late']:+.4f}")
mac("fastMlpLagCfourFinalSame", f"{r_mlplag['vs_same_wave_muont']['d_c4_final']:+.4f}")
mac("fastMlpLagCfourFinalAbs", f"{r_mlplag['c4_final']:.4f}")
mac("fastMlpLagSelLateAbs", f"{r_mlplag['sel_late']:.4f}")
mac("fastMlpLagWinOneSame", f"{r_mlplag['vs_same_wave_muont']['windows_detail'][0]['d_train']:+.4f}")
mac("fastMlpLagWinOneSeSame", f"{r_mlplag['vs_same_wave_muont']['windows_detail'][0]['se']:.4f}")
mac("fastMlpLagWinFiveSame", f"{r_mlplag['vs_same_wave_muont']['d_train']:+.4f}")
mac("fastMlpLagInFb", f"{r_mlplag['input_fallbacks']}")

# WT-Sym (no-lag, wave_sym_fastlag)
mac("symMlpSelSame", f"{r_sym['vs_same_wave_muont']['d_sel_late']:+.4f}")
mac("symMlpSelWaveZero", f"{r_sym['vs_wave0_muont']['d_sel_late']:+.4f}")
mac("symMlpSelFinalSame", f"{r_sym['vs_same_wave_muont']['d_sel_final']:+.4f}")
mac("symMlpCfourSame", f"{r_sym['vs_same_wave_muont']['d_c4_late']:+.4f}")
mac("symMlpCfourWaveZero", f"{r_sym['vs_wave0_muont']['d_c4_late']:+.4f}")
mac("symMlpCfourFinalSame", f"{r_sym['vs_same_wave_muont']['d_c4_final']:+.4f}")
mac("symMlpCfourFinalAbs", f"{r_sym['c4_final']:.4f}")
mac("symMlpWinOneSame", f"{r_sym['vs_same_wave_muont']['windows_detail'][0]['d_train']:+.4f}")
mac("symMlpWinOneSeSame", f"{r_sym['vs_same_wave_muont']['windows_detail'][0]['se']:.4f}")
mac("symMlpWinFiveSame", f"{r_sym['vs_same_wave_muont']['d_train']:+.4f}")
mac("symMlpInFb", f"{r_sym['input_fallbacks']}")

# WT-Sym-Lag (fast_lag, wave_sym_fastlag)
mac("symMlpLagSelSame", f"{r_symlag['vs_same_wave_muont']['d_sel_late']:+.4f}")
mac("symMlpLagSelWaveZero", f"{r_symlag['vs_wave0_muont']['d_sel_late']:+.4f}")
mac("symMlpLagSelFinalSame", f"{r_symlag['vs_same_wave_muont']['d_sel_final']:+.4f}")
mac("symMlpLagCfourSame", f"{r_symlag['vs_same_wave_muont']['d_c4_late']:+.4f}")
mac("symMlpLagCfourWaveZero", f"{r_symlag['vs_wave0_muont']['d_c4_late']:+.4f}")
mac("symMlpLagCfourFinalSame", f"{r_symlag['vs_same_wave_muont']['d_c4_final']:+.4f}")
mac("symMlpLagCfourFinalAbs", f"{r_symlag['c4_final']:.4f}")
mac("symMlpLagSelLateAbs", f"{r_symlag['sel_late']:.4f}")
mac("symMlpLagWinOneSame", f"{r_symlag['vs_same_wave_muont']['windows_detail'][0]['d_train']:+.4f}")
mac("symMlpLagWinOneSeSame", f"{r_symlag['vs_same_wave_muont']['windows_detail'][0]['se']:.4f}")
mac("symMlpLagWinFiveSame", f"{r_symlag['vs_same_wave_muont']['d_train']:+.4f}")
mac("symMlpLagInFb", f"{r_symlag['input_fallbacks']}")

# Head-to-head: WT-Sym-Lag vs. WT-MLP-Lag (same wave)
h_sl_ml = h2h["sym_mlpdiag_lag_vs_mlpdiag_lag_same_wave"]
mac("symLagVsMlpLagWinOne", f"{h_sl_ml['windows_detail'][0]['d_train']:+.4f}")
mac("symLagVsMlpLagWinOneSe", f"{h_sl_ml['windows_detail'][0]['se']:.4f}")
mac("symLagVsMlpLagWinTwo", f"{h_sl_ml['windows_detail'][1]['d_train']:+.4f}")
mac("symLagVsMlpLagWinThree", f"{h_sl_ml['windows_detail'][2]['d_train']:+.4f}")
mac("symLagVsMlpLagWinFour", f"{h_sl_ml['windows_detail'][3]['d_train']:+.4f}")
mac("symLagVsMlpLagWinFive", f"{h_sl_ml['windows_detail'][4]['d_train']:+.4f}")
mac("symLagVsMlpLagSelLate", f"{h_sl_ml['d_sel_late']:+.4f}")
mac("symLagVsMlpLagSelLateMag", f"{abs(h_sl_ml['d_sel_late']):.4f}")
mac("symLagVsMlpLagSelFinalMag", f"{abs(h_sl_ml['d_sel_final']):.4f}")
mac("symLagVsMlpLagCfourFinal", f"{h_sl_ml['d_c4_final']:+.4f}")

with open(os.path.join(HERE, "results", "derived_numbers.tex"), "w") as handle:
    handle.write("\n".join(out) + "\n")

print(f"wrote results/derived_numbers.tex ({len(out) - 1} macros)")
