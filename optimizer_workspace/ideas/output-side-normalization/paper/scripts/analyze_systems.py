mac("sysCapLegacyMs", f"{c['capture_ovh_legacy_mlpdiag']:.1f}")
mac("sysCapFastMlpMs", f"{c['capture_ovh_fast_mlpdiag']:.1f}")
mac("sysCapFastAllMs", f"{c['capture_ovh_fast_all']:.1f}")
mac("sysCapSpeedup", f"{c['capture_speedup_mlpdiag']:.1f}")

mac("sysUpdLegacyMlpMs", f"{c['upd_ovh_legacy_mlpdiag']:.1f}")
mac("sysUpdLegacyAllMs", f"{c['upd_ovh_legacy_all']:.1f}")
mac("sysUpdFastMlpMs", f"{c['upd_ovh_fast_mlpdiag']:.1f}")
mac("sysUpdFastAllMs", f"{c['upd_ovh_fast_all']:.1f}")

mac("sysRootsLegacyMlpMs", f"{c['roots_ovh_legacy_mlpdiag']:.1f}")
mac("sysRootsLegacyAllMs", f"{c['roots_ovh_legacy_all']:.0f}")
mac("sysRootsFastMlpLoMs", f"{c['roots_ovh_fast_mlpdiag_lo']:.1f}")
mac("sysRootsFastMlpHiMs", f"{c['roots_ovh_fast_mlpdiag_hi']:.1f}")
mac("sysRootsFastAllLoMs", f"{c['roots_ovh_fast_all_lo']:.0f}")
mac("sysRootsFastAllHiMs", f"{c['roots_ovh_fast_all_hi']:.0f}")

mac("sysMemSavedGib", f"{m['fast_mlpdiag_saved_gib']:.2f}")
mac("sysMemFastMlpGib", f"{m['fast_mlpdiag_8gpu_est_gib']:.2f}")
mac("sysTokenSavingPct", f"{p['token_saving_c4_352_pct']:.2f}")
mac("sysWallclockRatio", f"{p['projected_wallclock_ratio_c4_352']:.3f}")

with open(os.path.join(HERE, "results", "systems_numbers.tex"), "w") as handle:
    handle.write("\n".join(macros) + "\n")

