mac("sysFastMlpVsMuonMid", f"{t['fast_mlpdiag_lag_vs_muon_pct_mid']:.1f}")
mac("sysFastMlpVsMuontLo", f"{t['fast_mlpdiag_lag_vs_muont_pct_lo']:.1f}")
