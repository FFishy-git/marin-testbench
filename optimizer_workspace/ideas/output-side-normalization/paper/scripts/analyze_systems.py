"""Emit LaTeX macros, stage-breakdown table, and pgfplots data for the fast_lag systems section.

Reads results/systems_summary.json (calibrated SM80 A100 ABBA microbenchmarks,
isolated 32-layer memory profiles, and 24-step continuation parity checks) and writes:
  results/systems_numbers.tex
  results/table_systems.tex
  figs/systems_bars.dat

    python -I scripts/analyze_systems.py
"""

import json
import os

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

with open(os.path.join(HERE, "results", "systems_summary.json")) as handle:
    data = json.load(handle)

b = data["baselines_8gpu"]
c = data["calibrated_8gpu_ms"]
t = data["totals_8gpu"]
m = data["memory_32l_isolated"]
p = data["parity"]

