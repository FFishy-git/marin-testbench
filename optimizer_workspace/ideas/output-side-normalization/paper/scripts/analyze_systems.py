mac("sysFastAllVsMuonLo", f"{t['fast_all_lag_vs_muon_pct_lo']:.1f}")
mac("sysFastAllVsMuonHi", f"{t['fast_all_lag_vs_muon_pct_hi']:.1f}")
mac("sysFastAllVsMuonMid", f"{t['fast_all_lag_vs_muon_pct_mid']:.1f}")
mac("sysFastAllVsMuontLo", f"{t['fast_all_lag_vs_muont_pct_lo']:.1f}")
mac("sysFastAllVsMuontHi", f"{t['fast_all_lag_vs_muont_pct_hi']:.1f}")

mac("sysLegacyMlpVsMuon", f"{t['legacy_mlpdiag_lag_vs_muon_pct']:.1f}")
