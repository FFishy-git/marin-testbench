    f"MuonT (baseline) & $0.0$\\,ms & $0.0$\\,ms & $0.0$\\,ms & ${b['muont_step_s']:.3f}$ & $+{t['muont_vs_muon_pct']:.1f}$\\% & ${b['muont_mem_gib']:.2f}$ \\\\",
    "\\addlinespace",
    f"Legacy \\texttt{{all\\_lag}} (Wave 3) & $+{c['capture_ovh_legacy_mlpdiag']:.1f}$\\,ms & $+{c['upd_ovh_legacy_all']:.1f}$\\,ms & $+{c['roots_ovh_legacy_all']:.0f}$\\,ms & ${b['legacy_all_lag_step_s']:.3f}$ & $+{t['legacy_all_lag_vs_muon_pct']:.1f}$\\% & ${b['legacy_all_lag_mem_gib']:.2f}$ \\\\",
    f"Legacy \\texttt{{mlpdiag\\_lag}} (Wave 4) & $+{c['capture_ovh_legacy_mlpdiag']:.1f}$\\,ms & $+{c['upd_ovh_legacy_mlpdiag']:.1f}$\\,ms & $+{c['roots_ovh_legacy_mlpdiag']:.1f}$\\,ms & ${b['legacy_mlpdiag_lag_step_s']:.3f}$ & $+{t['legacy_mlpdiag_lag_vs_muon_pct']:.1f}$\\% & ${b['legacy_mlpdiag_lag_mem_gib']:.2f}$ \\\\",
