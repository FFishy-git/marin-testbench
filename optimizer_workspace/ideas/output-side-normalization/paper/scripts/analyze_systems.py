def fmt_cross(c_entry, bold=False):
    if c_entry["censored"]:
        return r"\textcolor{famAbl}{\textbf{Censored}} {\scriptsize($3.4618$)}"
    sec_str = fmt_thousands(c_entry["seconds"], 1)
    step_str = f"{c_entry['step']:,}".replace(",", "{,}")
    if bold:
        return rf"$\mathbf{{{sec_str}}}$\,\textbf{{s}} {{\scriptsize(step {step_str})}}"
    return rf"${sec_str}$\,s {{\scriptsize(step {step_str})}}"


