    "idx label input_base_ms capture_ms update_ms roots_ms total_pct_muon",
    f"0 MuonT {muont_base_ms:.1f} 0.0 0.0 0.0 {t['muont_vs_muon_pct']:.2f}",
    f"1 Legacy_all_lag {muont_base_ms:.1f} {c['capture_ovh_legacy_mlpdiag']:.1f} {c['upd_ovh_legacy_all']:.1f} {c['roots_ovh_legacy_all']:.1f} {t['legacy_all_lag_vs_muon_pct']:.2f}",
    f"2 Legacy_mlpdiag_lag {muont_base_ms:.1f} {c['capture_ovh_legacy_mlpdiag']:.1f} {c['upd_ovh_legacy_mlpdiag']:.1f} {c['roots_ovh_legacy_mlpdiag']:.1f} {t['legacy_mlpdiag_lag_vs_muon_pct']:.2f}",
