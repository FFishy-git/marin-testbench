"""Verify which run directories hold distinct training trajectories.

Several waves re-ran identical scientific configurations in order to measure
systems changes. Their recorded losses are bitwise identical to the originals,
so counting run directories overstates the independent evidence. This script
groups every run by its full 5,120-point training-loss trajectory and emits the
counts and the duplicate groups for the manuscript's evidence table.

    python -I scripts/check_duplicates.py
"""

import json
import os

PVC = "/apdcephfs_tj32/share_303214315/hunyuan/kenanchen/toner/output-side-normalization"
RUNS = os.path.join(PVC, "runs")
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def trajectory(path):
    values = []
    with open(path) as handle:
        for line in handle:
            line = line.strip()
            if line:
                values.append(round(json.loads(line)["train_loss"], 12))
    return tuple(values)


runs = []
for wave in sorted(os.listdir(RUNS)):
    wave_dir = os.path.join(RUNS, wave)
    if not os.path.isdir(wave_dir):
        continue
    for arm in sorted(os.listdir(wave_dir)):
        metrics = os.path.join(wave_dir, arm, "metrics_from_000000.jsonl")
        if os.path.exists(metrics):
            runs.append((f"{wave}/{arm}", metrics))

groups = {}
for name, metrics in runs:
    groups.setdefault(trajectory(metrics), []).append(name)

duplicates = sorted((g for g in groups.values() if len(g) > 1), key=len, reverse=True)

rows = []
for group in duplicates:
    kept = sorted(group)[0]
    rows.append((kept, len(group), ", ".join(r.split("/")[0] for r in sorted(group))))

with open(os.path.join(HERE, "results", "evidence_numbers.tex"), "w") as handle:
    handle.write("% Generated by scripts/check_duplicates.py. Do not edit.\n")
    handle.write(f"\\newcommand{{\\nRunDirs}}{{{len(runs)}}}\n")
    handle.write(f"\\newcommand{{\\nDistinctRuns}}{{{len(groups)}}}\n")
    handle.write(f"\\newcommand{{\\nDuplicateGroups}}{{{len(duplicates)}}}\n")
    handle.write(f"\\newcommand{{\\nDuplicateDirs}}{{{sum(len(g) for g in duplicates)}}}\n")

# The whole tabular is emitted; see the note in scripts/analyze.py about
# \input appending a \relax inside a tabular.
with open(os.path.join(HERE, "results", "table_duplicates.tex"), "w") as handle:
    handle.write("% Generated by scripts/check_duplicates.py. Do not edit.\n")
    handle.write("\\begin{tabular}{lrl}\n\\toprule\n")
    handle.write("Trajectory & Directories & Appears under \\\\\n\\midrule\n")
    for arm, count, waves in rows:
        handle.write(f"\\texttt{{{arm.replace('_', chr(92) + '_')}}} & {count} & {waves} \\\\\n")
    handle.write("\\bottomrule\n\\end{tabular}\n")

print(f"run directories: {len(runs)}")
print(f"distinct training trajectories: {len(groups)}")
print(f"duplicate groups: {len(duplicates)} covering {sum(len(g) for g in duplicates)} directories")
for group in duplicates:
    print("  ", sorted(group))
